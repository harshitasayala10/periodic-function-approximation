"""Training data for periodic function approximation.

Targets are generated by calling the black-box function. That call happens
only while building datasets and evaluation grids. Model inference must use
the trained network and must not call ``f``.
"""

import math
from typing import Tuple

import numpy as np
import torch
from torch.utils.data import DataLoader, Dataset

from .black_box import f

# Training domain required by the exercise. This is the sampling window,
# not the period of f.
TRAIN_X_MIN = -10.0 * math.pi
TRAIN_X_MAX = 10.0 * math.pi


class PeriodicFunctionDataset(Dataset):
    """Dataset of (x, f(x)) pairs drawn from the training domain."""

    def __init__(
        self,
        n_samples: int = 5000,
        strategy: str = "stratified",
        seed: int = 42,
        x_min: float = TRAIN_X_MIN,
        x_max: float = TRAIN_X_MAX,
    ) -> None:
        super().__init__()
        if n_samples < 1:
            raise ValueError(f"n_samples must be positive, got {n_samples}")
        if x_min >= x_max:
            raise ValueError(f"Expected x_min < x_max, got {x_min} >= {x_max}")

        self.n_samples = n_samples
        self.strategy = strategy
        self.seed = seed
        self.x_min = x_min
        self.x_max = x_max

        xs, ys = self._generate()
        # Shape (N, 1) so the network can use a matrix multiply.
        self.x = torch.tensor(xs, dtype=torch.float32).unsqueeze(1)
        self.y = torch.tensor(ys, dtype=torch.float32).unsqueeze(1)

    def _generate(self) -> Tuple[np.ndarray, np.ndarray]:
        rng = np.random.default_rng(self.seed)

        if self.strategy == "uniform":
            xs = rng.uniform(self.x_min, self.x_max, size=self.n_samples)
        elif self.strategy == "grid":
            xs = np.linspace(self.x_min, self.x_max, self.n_samples)
        elif self.strategy == "stratified":
            # One random point inside each equal-width slice of the domain.
            bins = np.linspace(self.x_min, self.x_max, self.n_samples + 1)
            xs = rng.uniform(bins[:-1], bins[1:])
        else:
            raise ValueError(
                f"Unknown strategy: '{self.strategy}'. "
                "Expected 'uniform', 'grid', or 'stratified'."
            )

        ys = np.array([f(float(x)) for x in xs], dtype=np.float64)
        return xs.astype(np.float64), ys

    def __len__(self) -> int:
        return self.n_samples

    def __getitem__(self, idx: int) -> Tuple[torch.Tensor, torch.Tensor]:
        return self.x[idx], self.y[idx]


def make_dataloaders(
    n_train: int = 5000,
    n_val: int = 1000,
    strategy: str = "stratified",
    batch_size: int = 256,
    seed: int = 42,
) -> Tuple[DataLoader, DataLoader]:
    """Create train and validation loaders.

    Validation uses ``seed + 1`` so it is held out from the training sample
    without overlapping the same random draw.
    """
    train_ds = PeriodicFunctionDataset(
        n_samples=n_train, strategy=strategy, seed=seed
    )
    val_ds = PeriodicFunctionDataset(
        n_samples=n_val, strategy=strategy, seed=seed + 1
    )

    generator = torch.Generator()
    generator.manual_seed(seed)
    train_loader = DataLoader(
        train_ds,
        batch_size=batch_size,
        shuffle=True,
        num_workers=0,
        generator=generator,
    )
    val_loader = DataLoader(
        val_ds,
        batch_size=batch_size,
        shuffle=False,
        num_workers=0,
    )
    return train_loader, val_loader


def make_eval_grid(
    x_min: float,
    x_max: float,
    n_points: int = 2000,
) -> Tuple[torch.Tensor, torch.Tensor]:
    """Dense grid of inputs and ground-truth targets for metrics and plots.

    This is the only place evaluation looks up ``f``. It is not used by
    inference. Compare ``predict`` in ``model.py``, which runs the network
    alone.
    """
    if n_points < 2:
        raise ValueError(f"n_points must be at least 2, got {n_points}")
    xs = np.linspace(x_min, x_max, n_points)
    ys = np.array([f(float(x)) for x in xs], dtype=np.float64)
    x_t = torch.tensor(xs, dtype=torch.float32).unsqueeze(1)
    y_t = torch.tensor(ys, dtype=torch.float32).unsqueeze(1)
    return x_t, y_t
